export type ImageAsset = {
  /** Output basename in src/assets/images/generated (e.g. `reception-counter-800.webp`). */
  key: string;
  /** Source file inside /media-source (never shipped). `null` = generate a studio luxury visual. */
  source: string | null;
  alt: string;
  /** True when a person (even partially) is visible. Listed in README. */
  containsPeople: boolean;
  /**
   * Face regions. Used twice:
   *  1. `npm run optimize-images` permanently blurs these pixels in every output file.
   *  2. <PrivacyBlur> renders a backdrop-filter overlay on top as defence in depth.
   */
  faceRegions: FaceRegion[];
  /** Responsive widths to generate (capped at the source width). */
  widths?: number[];
  /** Remove a white background (for logos supplied as JPG). Outputs PNG fallback. */
  knockoutWhite?: boolean;
  /** Bespoke luxury studio scene rendered locally by `optimize-images` when `source` is null. */
  studioScene?: StudioScene;
  studioCaption?: string;
  studioSub?: string;
};

